/**
 * ---------------------------------------------------------------
 * 📘 Built-in Tools in LangChain
 * ---------------------------------------------------------------
 *
 * Built-in tools wo tools hote hain
 * jo LangChain already provide karta hai.
 *
 * Matlab:
 * - Ye prebuilt hote hain
 * - Production-ready hote hain
 * - Aur inko use karne ke liye minimal setup chahiye hota hai
 *
 * Developer ko:
 * - Function khud nahi likhna padta
 * - Logic khud implement nahi karna padta
 *
 * Bas:
 * 👉 Tool ko import karo
 * 👉 Aur use karo
 *
 *
 * ---------------------------------------------------------------
 * ! Why Built-in Tools?
 * ---------------------------------------------------------------
 *
 * Built-in tools ka main purpose hai
 * common real-world tasks ko easily perform karna.
 *
 * Example:
 *
 * - Internet search
 * - API calls
 * - Running code
 * - Database queries
 * - Sending messages
 *
 * Ye sab kaam LLM khud nahi kar sakta,
 * lekin tools ki help se kar sakta hai.
 *
 *
 * ---------------------------------------------------------------
 * ! Examples of Built-in Tools
 * ---------------------------------------------------------------
 *
 * Kuch popular built-in tools LangChain mein:
 *
 * 🔹 DuckDuckGoSearchTool
 *    → Internet search karne ke liye
 *
 * 🔹 WikipediaQueryRun
 *    → Wikipedia se information retrieve karne ke liye
 *
 * 🔹 PythonREPLTool
 *    → Python code execute karne ke liye
 *
 * 🔹 ShellTool
 *    → Shell commands run karne ke liye
 *
 * 🔹 RequestsGetTool
 *    → External APIs ko GET request bhejne ke liye
 *
 * 🔹 GmailSendMessageTool
 *    → Gmail se email send karne ke liye
 *
 * 🔹 SlackSendMessageTool
 *    → Slack channel mein message bhejne ke liye
 *
 * 🔹 RequestsTool
 *    → General HTTP requests perform karne ke liye
 *
 * 🔹 RunShellCommandTool
 *    → System level shell commands run karne ke liye
 *
 * 🔹 SQLQueryTool
 *    → SQL database par queries run karne ke liye
 *
 *
 * ---------------------------------------------------------------
 * ! Key Idea
 * ---------------------------------------------------------------
 *
 * Built-in Tools:
 * - Already implemented hote hain
 * - Directly use kiye ja sakte hain
 *
 * Custom Tools:
 * - Developer khud define karta hai
 * - Python functions ko tool bana kar
 *   LLM ko use karne deta hai
 *
 *
 * ---------------------------------------------------------------
 * ! Final Insight
 * ---------------------------------------------------------------
 *
 * LangChain tools ka purpose hai
 * LLM ko real-world actions perform karne dena.
 *
 * Built-in tools use karke
 * hum quickly powerful AI agents build kar sakte hain.
 *
 */