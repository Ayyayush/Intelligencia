/**
 * ===============================================================
 * 🎯 Characteristic 2: Goal-Oriented (Agentic AI)
 * ===============================================================
 *
 * 📌 Definition:
 * Goal-Oriented behavior means that an AI system operates with a
 * persistent objective in mind and continuously directs its
 * actions toward achieving that objective, rather than responding
 * to isolated prompts.
 *
 * In Agentic AI:
 *   - The goal is always active
 *   - Every decision is evaluated against the goal
 *
 * ---------------------------------------------------------------
 * 🧭 Goal as a Compass
 * ---------------------------------------------------------------
 *
 * The goal acts as a compass for autonomy.
 *
 * It helps the agent decide:
 *   - What to do next
 *   - Which action is useful
 *   - Which action should be avoided
 *
 * Without a goal, autonomy becomes directionless.
 *
 * ---------------------------------------------------------------
 * 🔗 Goals with Constraints
 * ---------------------------------------------------------------
 *
 * Goals often come with constraints, such as:
 *   - Time limits
 *   - Budget limits
 *   - Quality thresholds
 *   - Policy or compliance rules
 *
 * Example:
 *   "Hire a backend engineer within 30 days
 *    under a fixed budget."
 *
 * ---------------------------------------------------------------
 * 🧠 Goal Storage (Core Memory)
 * ---------------------------------------------------------------
 *
 * In Agentic AI:
 *   - Goals are stored in core / long-term memory
 *   - They persist across multiple steps and actions
 *   - They guide planning and reasoning continuously
 *
 * ---------------------------------------------------------------
 * 🔄 Dynamic Goals
 * ---------------------------------------------------------------
 *
 * Goals are not always static.
 *
 * They can be:
 *   - Refined (add more clarity)
 *   - Updated (change constraints)
 *   - Replaced (new objective)
 *
 * A good agent can adapt when goals change
 * without restarting the entire process.
 *
 * ---------------------------------------------------------------
 * 🎯 One-Line Summary (Interview Ready)
 * ---------------------------------------------------------------
 *
 * Goal-orientation gives autonomy a direction
 * and prevents random or unnecessary actions.
 *
 * ===============================================================
 */