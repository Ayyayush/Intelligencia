/**
 * ===============================================================
 * 🧠 Characteristic 6: Context Awareness (Agentic AI)
 * ===============================================================
 *
 * 📌 Definition:
 * Context Awareness is the agent’s ability to understand,
 * retain, and relate information from:
 *   - The ongoing task
 *   - Past interactions
 *   - User preferences
 *   - The surrounding environment
 *
 * This allows the agent to make better decisions throughout
 * a multi-step workflow.
 *
 * In simple terms:
 *   The agent remembers what is happening and why.
 *
 * ---------------------------------------------------------------
 * 🧩 Types of Context
 * ---------------------------------------------------------------
 *
 * 1️⃣ Original Goal
 *    - The main objective driving the system
 *
 * 2️⃣ Progress Till Now
 *    - Completed steps
 *    - Pending actions
 *    - Intermediate results
 *
 * 3️⃣ Environment State
 *    - Tool availability
 *    - API responses
 *    - System conditions
 *
 * 4️⃣ Tool Responses
 *    - Output returned from external systems
 *    - Errors or success signals
 *
 * 5️⃣ User-Specific Preferences
 *    - Communication style
 *    - Constraints
 *    - Personalization settings
 *
 * 6️⃣ Policies / Guardrails
 *    - Safety constraints
 *    - Compliance rules
 *    - Permission boundaries
 *
 * ---------------------------------------------------------------
 * 🧠 How Context Awareness is Implemented
 * ---------------------------------------------------------------
 *
 * Context awareness is achieved through memory systems:
 *
 * 🔹 Short-Term Memory
 *    - Current session data
 *    - Immediate workflow state
 *
 * 🔹 Long-Term Memory
 *    - Historical interactions
 *    - Persistent preferences
 *    - Organizational knowledge
 *
 * ---------------------------------------------------------------
 * 🔁 Context in the Agent Loop
 * ---------------------------------------------------------------
 *
 *   Observe → Update Memory → Reason → Act
 *
 * Without context awareness:
 *   - Agent forgets progress
 *   - Repeats actions
 *   - Makes inconsistent decisions
 *
 * ---------------------------------------------------------------
 * 🎯 One-Line Summary (Interview Ready)
 * ---------------------------------------------------------------
 *
 * Context awareness enables consistent, intelligent decision-making
 * across long-running, multi-step tasks.
 *
 * ===============================================================
 */