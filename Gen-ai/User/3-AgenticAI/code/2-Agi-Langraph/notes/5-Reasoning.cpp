/**
 * ===============================================================
 * 🧠 Characteristic 4: Reasoning (Agentic AI)
 * ===============================================================
 *
 * 📌 Definition:
 * Reasoning is the cognitive process through which an Agentic AI
 * system interprets information, draws conclusions, and makes
 * decisions — both during planning and while executing actions
 * in real time.
 *
 * It is the "thinking" layer that connects planning with action.
 *
 * ---------------------------------------------------------------
 * 🧠 Reasoning During Planning
 * ---------------------------------------------------------------
 *
 * While planning ahead, reasoning helps the agent to:
 *
 *   1️⃣ Goal Decomposition
 *      - Break a high-level goal into smaller sub-goals
 *      - Decide logical ordering of steps
 *
 *   2️⃣ Tool Selection
 *      - Decide which tool is best suited for each step
 *      - Avoid unnecessary or risky tool calls
 *
 *   3️⃣ Resource Estimation
 *      - Estimate time, cost, and computational resources
 *      - Choose plans that fit constraints
 *
 * ---------------------------------------------------------------
 * ⚙️ Reasoning During Execution
 * ---------------------------------------------------------------
 *
 * While executing actions, reasoning enables:
 *
 *   1️⃣ Decision Making
 *      - Decide next action based on current state
 *      - Choose between retry, skip, or alternate path
 *
 *   2️⃣ HITL (Human-in-the-Loop) Handling
 *      - Decide when human approval is required
 *      - Escalate sensitive decisions
 *
 *   3️⃣ Error Handling
 *      - Interpret failures or unexpected results
 *      - Adjust plan or retry intelligently
 *
 * ---------------------------------------------------------------
 * 🔁 Continuous Reasoning Loop
 * ---------------------------------------------------------------
 *
 * Reasoning is continuous, not one-time.
 *
 *   Observe → Reason → Act → Observe → Reason → ...
 *
 * This loop continues until the goal is achieved or stopped.
 *
 * ---------------------------------------------------------------
 * 🎯 One-Line Summary (Interview Ready)
 * ---------------------------------------------------------------
 *
 * Reasoning enables an agent to make intelligent decisions
 * both before and during action execution.
 *
 * ===============================================================
 */