/**
 * ===============================================================
 * 🔄 Characteristic 5: Adaptability (Agentic AI)
 * ===============================================================
 *
 * 📌 Definition:
 * Adaptability is the agent’s ability to modify its plans,
 * strategies, or actions in response to unexpected situations,
 * while still staying aligned with the original goal.
 *
 * In simple terms:
 *   If something changes, the agent adjusts instead of stopping.
 *
 * ---------------------------------------------------------------
 * 🧠 Why Adaptability is Important
 * ---------------------------------------------------------------
 *
 * Real-world environments are unpredictable.
 *
 *   - APIs may fail
 *   - Tools may become unavailable
 *   - New constraints may appear
 *   - Goals may change
 *
 * Without adaptability, the agent would break.
 *
 * ---------------------------------------------------------------
 * ⚠️ Situations Requiring Adaptability
 * ---------------------------------------------------------------
 *
 * 1️⃣ Failures
 *    - Tool call fails
 *    - API timeout
 *    - Invalid output
 *
 *    Agent Response:
 *      → Retry
 *      → Switch tool
 *      → Re-plan
 *
 * ---------------------------------------------------------------
 *
 * 2️⃣ External Feedback
 *    - Human rejects a decision
 *    - User updates requirements
 *
 *    Agent Response:
 *      → Update state
 *      → Adjust plan accordingly
 *
 * ---------------------------------------------------------------
 *
 * 3️⃣ Changing Goals
 *    - New constraint added
 *    - Priority changes
 *    - Budget reduced
 *
 *    Agent Response:
 *      → Re-evaluate current plan
 *      → Generate new candidate plans
 *      → Continue execution
 *
 * ---------------------------------------------------------------
 * 🔁 Adaptability in the Agent Loop
 * ---------------------------------------------------------------
 *
 *   Plan → Execute → Observe → Detect Change → Adapt → Continue
 *
 * Adaptability ensures the agent does not rigidly follow
 * outdated instructions.
 *
 * ---------------------------------------------------------------
 * 🎯 One-Line Summary (Interview Ready)
 * ---------------------------------------------------------------
 *
 * Adaptability allows an agent to stay resilient and aligned
 * with the goal even when the environment changes.
 *
 * ===============================================================
 */