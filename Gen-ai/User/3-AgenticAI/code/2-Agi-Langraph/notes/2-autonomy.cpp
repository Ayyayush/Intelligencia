/**
 * ===============================================================
 * 🔑 Characteristic 1: Autonomy (Agentic AI)
 * ===============================================================
 *
 * 📌 Definition:
 * Autonomy refers to an AI system’s ability to take actions on its
 * own to achieve a given goal, without requiring step-by-step
 * human instructions.
 *
 * An autonomous agent:
 *   - Is proactive (does not wait for constant prompts)
 *   - Decides what to do next
 *   - Acts toward the goal independently
 *
 * ---------------------------------------------------------------
 * 🚀 Why Autonomy Matters
 * ---------------------------------------------------------------
 *
 * Autonomy enables Agentic AI to:
 *   - Execute multi-step workflows
 *   - Handle long-running tasks
 *   - Reduce human intervention
 *   - Operate efficiently at scale
 *
 * Without autonomy, an AI system is just a reactive chatbot.
 *
 * ---------------------------------------------------------------
 * 🧩 Autonomy Has Multiple Facets
 * ---------------------------------------------------------------
 *
 * Autonomy does NOT mean “no control”.
 * It exists at different levels and can be configured.
 *
 *   - Fully autonomous actions
 *   - Semi-autonomous actions
 *   - Human-approved actions
 *
 * ---------------------------------------------------------------
 * 🛑 Controlled Autonomy (Very Important)
 * ---------------------------------------------------------------
 *
 * Autonomy must always be controlled using:
 *
 * 🔹 Permission Scope
 *    - Defines what the agent is allowed to do
 *    - Example:
 *        • Read resumes ✔
 *        • Send emails ✔
 *        • Make payments ❌
 *
 * 🔹 HITL (Human-in-the-Loop)
 *    - Human approval required for sensitive actions
 *    - Example:
 *        • Final offer approval
 *        • Candidate rejection
 *
 * 🔹 Guardrails / Policies
 *    - Safety rules that the agent must follow
 *    - Prevents misuse or harmful behavior
 *
 * ---------------------------------------------------------------
 * ⚠️ Risks of Autonomy
 * ---------------------------------------------------------------
 *
 * If autonomy is poorly designed:
 *   - Agent may take unintended actions
 *   - Incorrect decisions may propagate
 *   - Security or compliance issues may occur
 *
 * Therefore:
 *   👉 Autonomy must be bounded, observable, and reversible.
 *
 * ---------------------------------------------------------------
 * 🎯 One-Line Summary (Interview Ready)
 * ---------------------------------------------------------------
 *
 * Autonomy makes agents powerful,
 * but controlled autonomy makes them safe.
 *
 * ===============================================================
 */